alert("Vamos descobrir a Area do Trapezio");
let baseMa = parseInt(prompt("Digite a Base maior do Trapezio: "));
let baseMe = parseInt(prompt("Digite a Base menor do Trapezio: "));
let altu = parseInt(prompt("Digite a altura do Trapezio"))
let area = ((baseMa + baseMe) *  altu) /2;
alert("A Área do Trapezio é" + area);
